// Run in an isolated Playwright CLI context; never against a user's live profile.
// npx --yes --package @playwright/cli playwright-cli run-code --filename=scripts/verify-fitness-v2-browser.mjs
async (page) => {
  const context = await page.context().browser().newContext({ viewport: { width: 320, height: 740 }, timezoneId: 'Europe/Dublin', acceptDownloads: true });
  const p = await context.newPage();
  const errors = [], passed = [];
  p.on('pageerror', e => errors.push(e.message));
  const check = (ok, name) => { if (!ok) throw Error(name); passed.push(name); };
  const db = () => p.evaluate(() => JSON.parse(localStorage.getItem('fitness-v2')));
  const url = 'http://127.0.0.1:8765/Fitness/plans/fitness-v2/index.html';
  try {
    await p.clock.install();
    await p.goto(url);
    await p.waitForFunction(() => document.querySelector('#offline-status').textContent.includes('Offline cache ready'));
    const legacy = await p.evaluate(() => {
      const raw = JSON.stringify({ schemaVersion: 1, sessions: [{ id: 'fake-browser-classic', workoutId: window.CURRENT_WORKOUT.id, startedAt: '2026-10-17T09:00:00Z', exerciseLogs: { [window.CURRENT_WORKOUT.steps[1].id]: { sets: [{ label:'Warm-up 1', load:'19.5 kg', reps:'9', completed:true }] } } }] }, null, 2);
      localStorage.setItem('fitness-coaching-runner-v1', raw); localStorage.removeItem('fitness-v2'); return raw;
    });
    await p.reload(); await p.locator('#choose').selectOption('sbd'); await p.locator('#start').click();
    check(await p.locator('h1').textContent() === 'Barbell squat', 'one exercise screen, SBD selected manually on Sunday');
    check(await p.locator('[id="0-load"]').inputValue() === '19.5 kg', 'migrated user load offered without marking complete');
    check(await p.locator('.set.done').count() === 0, 'suggested sets are not completed');
    check(await p.evaluate(raw => localStorage.getItem('fitness-coaching-runner-v1') === raw && localStorage.getItem('fitness-v2-classic-backup') === raw, legacy), 'exact Classic data and backup retained');
    await p.locator('[id="0-load"]').fill('18.5 kg');
    await p.locator('[data-step="1"][data-index="0"][data-key="load"]').click();
    check(await p.locator('[id="0-load"]').inputValue() === '19 kg', 'load stepper preserves Classic units');
    await p.locator('[data-step="-1"][data-index="0"][data-key="load"]').click();
    await p.locator('[id="0-reps"]').fill('10');
    await p.locator('[data-set="0"][data-action="complete"]').click();
    await p.reload();
    check(await p.locator('.set.done').count() === 1 && await p.locator('[id="0-load"]').inputValue() === '18.5 kg', 'field and completion survive reload');
    await p.locator('[data-set="0"][data-action="undo"]').click();
    check(await p.locator('.set.done').count() === 0, 'undo completion');
    await p.locator('[data-set="0"][data-action="complete"]').click();
    await p.locator('[data-set="1"][data-action="skip"]').click();
    check(await p.locator('.set.skipped').count() === 1, 'skip individual set');
    await p.locator('#jump').selectOption('2');
    check(await p.locator('h1').textContent() === 'Conventional deadlift', 'jump to arbitrary exercise');
    await p.locator('#back').focus(); await p.keyboard.press('Enter');
    check(await p.locator('h1').textContent() === 'Bench press', 'exercise navigation works by keyboard');
    await p.locator('#jump').selectOption('2');
    await p.locator('#skip-exercise').click();
    check(await p.locator('#unskip').isVisible(), 'skip exercise');
    await p.locator('#unskip').click();
    await p.locator('#quit').click(); await p.locator('[data-resume]').click();
    check(await p.locator('h1').textContent() === 'Conventional deadlift', 'quit and resume at saved exercise');
    await p.locator('#timer-toggle').click();
    let timer = (await db()).timer;
    check(timer.state === 'running' && timer.endAt > Date.now(), '90-second timer persists deadline');
    const end = timer.endAt;
    await p.locator('#timer-plus').click();
    check((await db()).timer.endAt === end + 15000, 'add 15 seconds');
    await p.locator('#timer-minus').click();
    check((await db()).timer.endAt === end, 'subtract 15 seconds');
    await p.locator('#next').click();
    check((await db()).timer.endAt === end, 'navigation does not change timer');
    await p.reload(); check((await db()).timer.endAt === end, 'timer survives refresh');
    await p.locator('#timer-toggle').click(); timer = (await db()).timer;
    check(timer.state === 'paused' && timer.pausedRemainingMs > 0, 'timer pause persisted');
    await p.reload(); check((await db()).timer.state === 'paused', 'paused timer survives reload');
    await p.locator('#timer-toggle').click(); check((await db()).timer.state === 'running', 'timer resumes');
    await p.locator('#timer-reset').click(); check((await db()).timer.pausedRemainingMs === 90000, 'timer reset uses saved default');
    await p.locator('#timer-toggle').click(); await p.clock.fastForward(5000);
    const wallBeforeRollback = await p.evaluate(() => Date.now());
    await p.clock.setSystemTime(new Date(wallBeforeRollback - 60000));
    await p.locator('#timer-toggle').click();
    check((await db()).timer.pausedRemainingMs <= 85500, 'monotonic correction survives pause after backwards wall clock change');
    await p.clock.setSystemTime(new Date(wallBeforeRollback)); await p.locator('#timer-reset').click();
    // Instrument Web Audio scheduling, not the physical speaker output.
    await p.evaluate(() => {
      window.__cues = 0;
      const original = AudioContext.prototype.createOscillator;
      AudioContext.prototype.createOscillator = function() { const o = original.call(this); const start = o.start.bind(o); o.start = (...args) => { window.__cues++; return start(...args); }; return o; };
    });
    await p.locator('#timer-toggle').click();
    // Use the browser's virtual clock to exercise callbacks quickly.
    await p.clock.fastForward(91000);
    check((await db()).timer.state === 'expired', 'active-page expiry at absolute deadline');
    check(await p.evaluate(() => window.__cues) === 3, 'Web Audio oscillator cues scheduled on active page');
    const alertId = (await db()).timer.alertedId;
    await p.reload(); check((await db()).timer.alertedId === alertId && (await db()).timer.state === 'expired', 'expiry ID retained without repeated resume cue');
    await p.clock.resume();
    await p.locator('#summary').click();
    check(await p.locator('textarea').count() === 1, 'summary has exactly one optional Comments field');
    await p.locator('#comments').fill('Énergie 💪 — invented test comment');
    p.once('dialog', d => d.accept()); await p.locator('#finish').click();
    check((await db()).sessions[0].status === 'completed', 'finish with explicitly confirmed missing sets');
    await p.locator('[data-history]').click(); await p.locator('#edit').click(); await p.locator('#jump').selectOption('0');
    await p.locator('[id="0-reps"]').fill('11'); await p.locator('#summary').click();
    check((await db()).sessions[0].audit.some(a => a.action === 'set-edit' && a.after === '11'), 'history editing records audit');
    await p.getByRole('button', { name:'Settings & backup', exact:true }).click();
    await p.locator('#rest-default').fill('60'); await p.locator('#rest-default').dispatchEvent('change');
    check((await db()).settings.restSeconds === 60, 'adjustable default interval');
    const beforeImport = await db();
    const downloadPromise = p.waitForEvent('download'); await p.locator('#export').click();
    const download = await downloadPromise, stream = await download.createReadStream(), chunks = [];
    for await (const chunk of stream) chunks.push(chunk);
    const exported = JSON.parse(Buffer.concat(chunks).toString('utf8'));
    check(exported.sessions[0].comments === 'Énergie 💪 — invented test comment' && exported.legacyRaw === legacy, 'export contains Unicode and exact Classic snapshot');
    const upload = async value => {
      await p.locator('#import-file').setInputFiles({ name:'fake-backup.json', mimeType:'application/json', buffer:Buffer.from(typeof value === 'string' ? value : JSON.stringify(value)) });
      await p.waitForFunction(() => /^Import (complete|rejected|cancelled)/.test(document.querySelector('#import-status').textContent));
    };
    await upload('{bad'); check((await p.locator('#import-status').textContent()).includes('rejected'), 'malformed JSON rejected');
    const altered = structuredClone(exported); altered.sessions[0].comments = 'Incoming É 💪';
    p.once('dialog', d => d.dismiss()); await upload(altered);
    check((await db()).sessions[0].comments === beforeImport.sessions[0].comments, 'cancelled import changes nothing');
    p.once('dialog', d => d.accept()); await upload(altered);
    check((await db()).sessions[0].comments === 'Incoming É 💪', 'confirmed merge import roundtrip');
    check(await p.evaluate(() => JSON.parse(localStorage.getItem('fitness-v2-before-import')).sessions[0].comments) === beforeImport.sessions[0].comments, 'pre-import recovery copy exists');
    await p.locator('#import-mode').selectOption('replace');
    p.once('dialog', d => d.accept()); await upload(exported);
    check((await db()).sessions[0].comments === exported.sessions[0].comments, 'confirmed replacement import roundtrip');
    await p.locator('[data-setting=autoRest]').check();
    await p.getByRole('button', { name:'Today', exact:true }).click(); await p.locator('#choose').selectOption('indoor-b'); await p.locator('#start').click();
    check(await p.locator('.set').count() === 2, 'indoor B begins with two sets');
    await p.locator('[id="0-reps"]').fill('12'); await p.locator('[data-set="0"][data-action="complete"]').click();
    check((await db()).timer.state === 'running', 'enabled auto-rest starts after first set');
    await p.locator('#timer-reset').click();
    await p.locator('[id="1-reps"]').fill('11'); await p.locator('[data-set="1"][data-action="complete"]').click();
    check((await db()).timer.state === 'idle', 'auto-rest does not start after final set');
    await p.locator('#jump').selectOption('1');
    check(await p.locator('[id="0-rightReps"]').count() === 1, 'side-specific reps available without extra sets');
    await p.locator('[id="0-reps"]').fill('10'); await p.locator('[id="0-rightReps"]').fill('9');
    await p.locator('#add-set').click(); check(await p.locator('.set').count() === 3, 'sets increase only by manual action');
    await p.locator('#jump').selectOption('2'); check(await p.locator('select[data-key=variation]').count() === 2, 'triceps variant choice');
    await p.locator('#next').scrollIntoViewIfNeeded();
    check(await p.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), '320px layout has no horizontal overflow');
    check(await p.evaluate(() => document.querySelector('#next').getBoundingClientRect().bottom <= document.querySelector('#timer').getBoundingClientRect().top), 'last navigation scrolls above timer dock');
    check(await p.evaluate(() => [...document.querySelectorAll('button,input,select,textarea')].filter(e => e.getBoundingClientRect().height && e.tagName !== 'INPUT').every(e => e.getBoundingClientRect().height >= 44)), 'visible controls meet 44px minimum height');
    await p.screenshot({path:'output/playwright/fitness-v2-exercise-320.png',fullPage:true});
    await p.emulateMedia({colorScheme:'dark'}); await p.setViewportSize({width:390,height:844}); await p.evaluate(() => window.scrollTo(0,0));
    await p.screenshot({path:'output/playwright/fitness-v2-exercise-dark-390.png'});
    await p.emulateMedia({colorScheme:'light'}); await p.setViewportSize({width:1280,height:900});
    check(await p.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'desktop layout has no horizontal overflow');
    await p.locator('#summary').click(); await p.screenshot({path:'output/playwright/fitness-v2-summary-desktop.png'});
    p.once('dialog', d => d.accept()); await p.locator('#finish').click();
    check((await db()).sessions[0].comments === '', 'empty comment saves successfully');
    await p.getByRole('button', { name:'Today', exact:true }).click(); await p.locator('#choose').selectOption('indoor-a'); await p.locator('#start').click();
    check(await p.locator('h1').textContent() === 'Band lateral raises', 'indoor A manually selectable');
    await context.setOffline(true); await p.reload();
    check(await p.locator('h1').textContent() === 'Band lateral raises', 'offline cached reload at GitHub Pages subpath with draft');
    await p.locator('[id="0-reps"]').fill('15');
    check((await db()).sessions[0].exercises[0].sets[0].reps === '15', 'offline edits persist');
    await context.setOffline(false);
    const other = await context.newPage(); await other.goto('http://127.0.0.1:8765/Fitness/plans/todays-workout.html');
    await other.waitForURL('**/fitness-v2/index.html');
    check(other.url() === url, 'existing public workout entry resolves to v2 at project subpath');
    await other.locator('[id="0-reps"]').fill('16');
    await p.waitForFunction(() => document.querySelector('#storage-status').textContent.includes('Another tab'));
    check(await p.locator('#storage-status').evaluate(e => e.classList.contains('error')), 'concurrent-tab conflict is visible');
    await other.close(); await p.reload();
    // Deliberate quota failure affects this isolated test context only.
    await p.evaluate(() => { const set = Storage.prototype.setItem; window.__set = set; Storage.prototype.setItem = function(k,v) { if(k === 'fitness-v2') throw new DOMException('Test quota exceeded','QuotaExceededError'); return set.call(this,k,v); }; });
    await p.locator('[id="0-reps"]').fill('17');
    check((await p.locator('#storage-status').textContent()).includes('NOT SAVED'), 'storage write failure is visible');
    check((await db()).sessions[0].exercises[0].sets[0].reps === '16', 'failed write does not overwrite prior stored record');
    await p.evaluate(() => { Storage.prototype.setItem = window.__set; localStorage.setItem('fitness-v2','{broken'); });
    await p.reload();
    check((await p.locator('h1').textContent()).includes('needs attention'), 'corrupt stored database blocks startup');
    check(await p.evaluate(() => localStorage.getItem('fitness-v2')) === '{broken', 'corrupt original remains untouched');
    check(errors.length === 0, `no uncaught browser errors (${errors.join('; ')})`);
    return {passed:passed.length, checks:passed};
  } finally { await context.close(); }
}
